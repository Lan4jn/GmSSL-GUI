package org.gmssl.gui.platform;

import java.nio.charset.StandardCharsets;
import java.util.*;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionTemplate;

@Component
class Materials {
  final Store s;
  final Vault vault;
  final TransactionTemplate tx;
  final CredentialService credentials;

  Materials(Store s, Vault v, TransactionTemplate tx, CredentialService credentials) {
    this.s = s;
    vault = v;
    this.tx = tx;
    this.credentials = credentials;
  }

  Map<String, Object> raw(String pid, String id) {
    return s.one("select * from materials where project_id=? and id=?", pid, id);
  }

  Map<String, Object> raw(String pid, String id, String type) {
    var m = raw(pid, id);
    if (!type.equals(m.get("object_type"))) throw ApiError.missing();
    return m;
  }

  Map<String, Object> dto(Map<String, Object> m) {
    var r = new LinkedHashMap<String, Object>();
    String id = m.get("id").toString();
    r.put("id", id);
    r.put("name", m.get("name"));
    r.put("createdAt", m.get("created_at"));
    if ("KEY".equals(m.get("object_type"))) {
      r.put("projectId", m.get("project_id"));
      for (String[] pair :
          new String[][] {
            {"algorithm", "algorithm"},
            {"keyKind", "key_kind"},
            {"encoding", "encoding"},
            {"usage", "usage_text"},
            {"description", "description"},
            {"publicFingerprint", "fingerprint"},
            {"updatedAt", "updated_at"},
            {"stateful", "stateful"}
          }) r.put(pair[0], m.get(pair[1]));
      r.put("validationStatus", "UNVERIFIED");
      r.put("generationProvider", m.get("generation_provider"));
      r.put("hasManagedPassphrase", credentials.hasPassphrase(id));
    } else {
      r.put("size", m.get("byte_size"));
      r.put("mediaType", m.get("media_type"));
      r.put("temporary", Store.bool(m, "temporary"));
      r.put("generationProvider", m.get("generation_provider"));
      r.put("hasManagedPassphrase", credentials.hasPassphrase(id));
    }
    return r;
  }

  Map<String, Object> create(
      String pid, String type, String name, String media, byte[] data, Map<String, String> b) {
    if ("STATEFUL_PRIVATE_KEY".equals(b.get("keyKind")))
      throw ApiError.bad("Stateful keys must be generated by a controlled platform task");
    return createControlled(pid, type, name, media, data, b);
  }

  Map<String, Object> createControlled(
      String pid, String type, String name, String media, byte[] data, Map<String, String> b) {
    name = AccountController.bounded(name, 200, true).replaceAll("[\\r\\n\\x00]", "_");
    if (data.length > Vault.LIMIT)
      throw new ApiError(413, "TOO_LARGE", "Material exceeds size limit");
    String id = s.id(),
        now = s.now(),
        kind = b.get("keyKind"),
        algo = b.get("algorithm"),
        encoding = b.get("encoding");
    if (type.equals("KEY")) {
      if (!Set.of(
              "PRIVATE_KEY", "PUBLIC_KEY", "SYMMETRIC_KEY", "MASTER_KEY", "STATEFUL_PRIVATE_KEY")
          .contains(kind)) throw ApiError.bad("Invalid key kind");
      AccountController.bounded(algo, 100, true);
      if (encoding == null)
        encoding =
            new String(data, 0, Math.min(data.length, 32), StandardCharsets.US_ASCII)
                    .startsWith("-----BEGIN ")
                ? "PEM"
                : "RAW";
      if (!Set.of("PEM", "DER", "RAW", "HEX", "TEXT").contains(encoding))
        throw ApiError.bad("Invalid key encoding");
      if (encoding.equals("HEX")) {
        String h = new String(data, StandardCharsets.US_ASCII).trim();
        if (!h.matches("(?:[0-9a-fA-F]{2})+")) throw ApiError.bad("Invalid HEX material");
      }
    }
    String enc = encoding;
    String n = name;
    boolean temp = "true".equalsIgnoreCase(b.getOrDefault("temporary", "false"));
    if (temp && !"FILE".equals(type)) {
      throw ApiError.bad("Temporary is only allowed for FILE");
    }
    vault.write(pid, id, data, false);
    try {
      tx.executeWithoutResult(
          t -> {
            if ("STATEFUL_PRIVATE_KEY".equals(kind)) registerState(id, data);
            s.db.update(
                "insert into materials("
                    + "id,project_id,object_type,name,media_type,byte_size,algorithm,key_kind,"
                    + "encoding,usage_text,description,fingerprint,stateful,pending,created_at,updated_at,temporary,bound_job_id,generation_provider)"
                    + " values(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,null,?)",
                id,
                pid,
                type,
                n,
                media,
                data.length,
                algo,
                kind,
                enc,
                AccountController.bounded(b.getOrDefault("usage", ""), 500, false),
                AccountController.bounded(b.getOrDefault("description", ""), 2000, false),
                null,
                "STATEFUL_PRIVATE_KEY".equals(kind),
                false,
                now,
                now,
                temp,
                b.get("generationProvider"));
          });
    } catch (RuntimeException e) {
      vault.delete(id);
      throw e;
    }
    return dto(raw(pid, id));
  }

  void registerState(String id, byte[] bytes) {
    String digest = vault.statefulDigest(bytes);
    var found = s.rows("select material_id from stateful_material_history where digest=?", digest);
    if (!found.isEmpty()) {
      if (!id.equals(found.getFirst().get("material_id")))
        throw new ApiError(409, "STATEFUL_DUPLICATE", "Stateful material was previously imported");
      return;
    }
    try {
      s.db.update("insert into stateful_material_history values(?,?,?)", digest, id, s.now());
    } catch (org.springframework.dao.DuplicateKeyException e) {
      throw new ApiError(409, "STATEFUL_DUPLICATE", "Stateful material was previously imported");
    }
  }

  void delete(String pid, String id) {
    tx.executeWithoutResult(
        t -> {
          var m = s.one("select * from materials where project_id=? and id=? for update", pid, id);
          if (Store.bool(m, "pending"))
            throw new ApiError(409, "KEY_PENDING", "Stateful key requires recovery");
          if (m.get("bound_job_id") != null) {
            var activeJobs =
                s.rows(
                    "select id from jobs where id=? and status in ('QUEUED','RUNNING')",
                    m.get("bound_job_id"));
            if (!activeJobs.isEmpty()) {
              throw new ApiError(409, "FILE_BOUND", "Temporary file is currently in use by a task");
            }
          }
          vault.delete(id);
          s.db.update("delete from artifacts where id=?", id);
          s.db.update("delete from key_credentials where material_id=?", id);
          s.db.update("delete from materials where id=? and project_id=?", id, pid);
        });
  }
}
